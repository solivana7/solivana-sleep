"use client";

import { useEffect, useRef, useState } from "react";
import { BINAURAL_PROTOCOLS, playBinaural, type BinauralHandle, type BinauralProtocol } from "@/lib/audio";

// Client-only — Web Audio API requires window. Lazy-instantiates the
// AudioContext on the first play (autoplay policy compliance).
export function BinauralPlayer() {
  const [activeId, setActiveId] = useState<BinauralProtocol["id"] | null>(null);
  const [volume, setVolumeState] = useState(0.55);
  const handleRef = useRef<BinauralHandle | null>(null);

  // Live volume — drag the slider while audio is playing and the gain
  // smooth-ramps (~150ms) in real time. Without this the slider only
  // affected the next play.
  function setVolume(v: number) {
    setVolumeState(v);
    handleRef.current?.setVolume(v);
  }

  // Stop on unmount or tab hidden
  useEffect(() => {
    const stop = () => { handleRef.current?.stop(); handleRef.current = null; setActiveId(null); };
    const onHide = () => { if (document.hidden) stop(); };
    document.addEventListener("visibilitychange", onHide);
    return () => {
      document.removeEventListener("visibilitychange", onHide);
      stop();
    };
  }, []);

  function toggle(p: BinauralProtocol) {
    if (activeId === p.id) {
      handleRef.current?.stop();
      handleRef.current = null;
      setActiveId(null);
      return;
    }
    handleRef.current?.stop();
    try {
      handleRef.current = playBinaural(p, volume);
      setActiveId(p.id);
    } catch {
      setActiveId(null);
    }
  }

  return (
    <div className="space-y-6">
      <div className="card card--warm">
        <p className="eyebrow mb-2">Headphones required</p>
        <p className="text-sm text-mid leading-relaxed">
          Binaural protocols rely on a small frequency offset between left and
          right ears. Without headphones, the brain can&apos;t lock onto the beat
          and the effect doesn&apos;t happen. Educational use only.
        </p>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
        {BINAURAL_PROTOCOLS.map((p) => {
          const playing = activeId === p.id;
          return (
            <button
              key={p.id}
              onClick={() => toggle(p)}
              aria-pressed={playing}
              className={`card text-left transition-shadow hover:shadow-elevated ${playing ? "ring-2 ring-amber" : ""}`}
            >
              <div className="flex items-center justify-between mb-2">
                <p className="eyebrow">{p.durationMin} minutes</p>
                <span
                  className={`inline-flex items-center justify-center w-8 h-8 rounded-full ${playing ? "bg-amber text-ink" : "bg-bark/5 text-bark"}`}
                  aria-hidden="true"
                >
                  {playing ? (
                    <svg width="14" height="14" viewBox="0 0 14 14" fill="currentColor"><rect x="3" y="2" width="3" height="10" /><rect x="8" y="2" width="3" height="10" /></svg>
                  ) : (
                    <svg width="14" height="14" viewBox="0 0 14 14" fill="currentColor"><polygon points="3,2 12,7 3,12" /></svg>
                  )}
                </span>
              </div>
              <h3 className="font-sans text-bark text-lg font-medium mb-1">{p.name}</h3>
              <p className="text-sm text-mid leading-relaxed">{p.description}</p>
              <p className="mt-2 text-xs text-mid/80 font-mono">
                {p.carrierHz} Hz carrier · {p.offsetHz} Hz beat
              </p>
            </button>
          );
        })}
      </div>

      <label className="block">
        <span className="eyebrow block mb-2 flex justify-between items-baseline">
          <span>Volume</span>
          <span className="text-mid/80 normal-case tracking-normal text-xs">
            {Math.round(volume * 100)}%
          </span>
        </span>
        <input
          type="range"
          min={0}
          max={1}
          step={0.01}
          value={volume}
          onChange={(e) => setVolume(parseFloat(e.target.value))}
          aria-valuemin={0}
          aria-valuemax={1}
          aria-valuenow={volume}
          aria-valuetext={`${Math.round(volume * 100)} percent`}
          className="w-full accent-amber"
        />
        <p className="mt-2 text-xs text-mid">
          Start around 50–70%. Sine waves are perceptually quieter than music —
          use your headphone hardware volume too. If you can&apos;t hear it
          on laptop speakers, that&apos;s expected; the beat needs headphones.
        </p>
      </label>

      <p className="text-xs text-mid italic">
        Generated by SoliVana AI · Educational audio, not medical treatment.
      </p>
    </div>
  );
}
